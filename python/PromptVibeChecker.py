from typing import Any

def PromptVibeCheck(prompt: str) -> bool:
    """
    Возвращает True, если тема НЕПРИЕМЛЕМА (unethical)
    """

    response: Any = chat(
        model="gpt-oss:20b-cloud",
        messages=[
            {
                "role": "system",
                "content": (
                    "Ты — автоматическая система модерации тем.\n"
                    "Твоя задача — строго определить, является ли тема неприемлемой.\n\n"
                    "Правила:\n"
                    "- Решение должно быть максимально строгим.\n"
                    "- Если есть сомнение — считай тему неприемлемой.\n"
                    "- Образовательный, научный, лингвистический или исторический контекст "
                    "НИКОГДА не делает тему допустимой.\n"
                    "- Ты НЕ объясняешь решение и НЕ добавляешь комментарии."
                ),
            },
            {
                "role": "user",
                "content": (
                    "Определи, является ли тема неприемлемой.\n\n"
                    "Тема считается НЕПРИЕМЛЕМОЙ, если выполняется ХОТЯ БЫ ОДНО условие:\n\n"
                    "1. Тема содержит нецензурную лексику\n"
                    "   ИЛИ предполагает её обсуждение, анализ, описание или классификацию\n"
                    "   ИЛИ содержит слова, образованные от корней:\n"
                    "   - мат\n"
                    "   - матер\n"
                    "   - нецензур\n"
                    "   - бран\n"
                    "   - ругат\n"
                    "   - обсцен\n"
                    "   - ненорматив\n\n"
                    "2. Тема содержит или подразумевает контент для взрослых.\n"
                    "3. Тема связана с политикой или политическими процессами.\n"
                    "4. Тема нарушает законодательство.\n"
                    "5. Тема противоречит общепринятым моральным и этическим нормам.\n\n"
                    "Даже если тема сформулирована нейтрально или без явных запрещённых слов,\n"
                    "но подразумевает перечисленные категории, она всё равно считается неприемлемой.\n\n"
                    "Ответь СТРОГО в формате JSON, без дополнительного текста:\n"
                    "{ \"unethical\": true | false }\n\n"
                    "Тема: " + prompt
                ),
            },
        ],
    )

    try:
        content = response["message"]["content"]

        if isinstance(content, dict) and "unethical" in content:
            return bool(content["unethical"])

    except Exception:
        pass

    return True
